"""One short-lived CPU worker per upload: no persistent OCR engine or user logs.

Invocation is internal; paths are generated by the backend, not uploaded filenames.
"""
import argparse
import json
import os
from pathlib import Path
import sys

PROFILES = {'en': 'en_PP-OCRv5_mobile_rec', 'hi': 'devanagari_PP-OCRv5_mobile_rec', 'te': 'te_PP-OCRv5_mobile_rec'}
DETECTOR = 'PP-OCRv5_mobile_det'


def engine(language, root, bootstrap=False):
    os.environ['PADDLE_PDX_DISABLE_MODEL_SOURCE_CHECK'] = 'True'
    os.environ['OMP_NUM_THREADS'] = '1'
    os.environ['OPENBLAS_NUM_THREADS'] = '1'
    from paddleocr import PaddleOCR
    model = PROFILES[language]
    args = dict(text_detection_model_name=DETECTOR, text_recognition_model_name=model,
                use_doc_orientation_classify=False, use_doc_unwarping=False, use_textline_orientation=False,
                device='cpu', cpu_threads=1, enable_mkldnn=False, text_rec_score_thresh=0.0,
                text_det_limit_side_len=1600, text_det_limit_type='max')
    if not bootstrap:
        args.update(text_detection_model_dir=str(root / DETECTOR), text_recognition_model_dir=str(root / model))
    return PaddleOCR(**args)


def predict(language, root, path, predictor=None):
    from importlib.metadata import version
    predictor = predictor if predictor is not None else engine(language, root)
    output = []
    for page in predictor.predict(str(path)):
        texts, scores, boxes = page['rec_texts'], page['rec_scores'], page['rec_polys']
        for index, text in enumerate(texts):
            if not text.strip(): continue
            output.append({'text': text, 'confidence': float(scores[index]) if scores is not None else None,
                           'bounding_box': {'points': boxes[index].tolist()}, 'language_model': language, 'model': PROFILES[language]})
    return {'regions': output, 'package_version': version('paddleocr'), 'runtime_version': version('paddlepaddle'),
            'detector': DETECTOR, 'recognizer': PROFILES[language]}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--language', choices=PROFILES, required=True)
    parser.add_argument('--model-root', required=True)
    parser.add_argument('--input')
    parser.add_argument('--output')
    parser.add_argument('--bootstrap', action='store_true')
    args = parser.parse_args()
    if args.bootstrap:
        engine(args.language, Path(args.model_root), bootstrap=True)
        return
    try:
        result = predict(args.language, Path(args.model_root), args.input)
    except Exception as exc:
        result = {'error': type(exc).__name__, 'regions': []}
    Path(args.output).write_text(json.dumps(result, ensure_ascii=False))


if __name__ == '__main__': main()
